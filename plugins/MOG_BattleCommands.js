/**
 * @param {Sprite} sprite
 * @param {number} index
 */
Window_ActorCommand.prototype.spriteMoveRadial = function(sprite, index) {
	const poseOffset = this.getWheelPositionOffset(Karryn.poseName);
	const centerX = (this.width / 2) + REM_BHD_BC_COM_X + poseOffset.x;
	const centerY = (this.height / 2) + REM_BHD_BC_COM_Y + poseOffset.y;

	const itemAngle = Math.PI - (this._currentAngle + 2 * Math.PI * index / this.maxCom());
	sprite.x = centerX + Math.sin(itemAngle) * this._rol_range;
	sprite.y = centerY + Math.cos(itemAngle) * this._rol_range;
}

Window_ActorCommand.prototype.sprite_move_to = function(value, real_value, speed) {
	if (value === real_value) {
		return value;
	}

	const dnspeed = (5 + (Math.abs(value - real_value) / speed)) * 60 * SceneManager._deltaTime;
	if (value > real_value) {
		value -= dnspeed;
		if (value < real_value) {
			value = real_value;
		}
	} else if (value < real_value) {
		value += dnspeed;
		if (value > real_value) {
			value = real_value;
		}
	}

	return Math.floor(value);
};

