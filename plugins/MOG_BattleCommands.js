Window_ActorCommand.prototype.update_battle_commands = function() {
	if (this.needResetCom()) {
	   if (this._actor) {
		   this.battle_commands_initialize();
	   }
	   return;
	}
	this.contentsOpacity = 0;
	this.opacity = 0;
	if (this._com_index !== this._index) {
		this.refresh_index();
	}

	for (let i = 0; i < this._com_sprites.length; i++) {
		if (i <= this.maxCom()) {
		    this._com_sprites[i].visible = true;
			this.update_commands(i);
		} else {
			this._com_sprites[i].opacity = 0;
			this._com_sprites[i].visible = false;
	    }
	}

	if (this._old_visible !== this.visible) {
		this.position_clear();
	}
	if (this._arrow) {
		this.update_arrow();
	}
	if (this._cursor_b) {
		this.update_cursor_b();
	}
	const delta = this.com_fade_speed() * 60 * SceneManager._deltaTime;
	if (this._com_name) {
		this._com_name.opacity += delta;
	}
	this._layout.opacity += delta;
	this.update_input_commands();
	if (this._com_mode_b === 0 && this._wh && this._wh[1] === 0) {
		this.refresh_bitmap_com();
		if (this._arrow) {
			this.refresh_arrow_position();
		}
	}
};

