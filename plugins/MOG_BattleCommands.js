//==============================
// * Update On Index
//==============================
Window_ActorCommand.prototype.update_on_index = function(i) {
	this._side[i] = [this._side_m[0], this._side_m[1]];
	const sprite = this._com_sprites[i];
	this._cursor_nxy = [sprite.x - (sprite.bitmap.width / 2), sprite.y];
	sprite.opacity = Math.max(1, sprite.opacity + this.com_fade_speed() * 60 * SceneManager._deltaTime);
	if (this._zoom_effect) {
		this.update_zoom_effect(i);
	}
};

//==============================
// * Update Off Index (i.e. not selected menu element)
//==============================
Window_ActorCommand.prototype.update_off_index = function (i) {
	this._side[i] = [0, 0];

	const unselectedOpacity = this.translucentOpacity();
	const hiddenOpacity = 0;
	const sprite = this._com_sprites[i];
	const delta = 60 * SceneManager._deltaTime;
	const fadeDelta = this.com_fade_speed() * delta;

	const maxVisibleRows = this.limit_rows_sp();
	const isVerticalMenu = this._com_mode_b === 0;
	const minVisible = isVerticalMenu ? Math.max(0, this._index - maxVisibleRows) : 0;
	const maxVisible = minVisible + maxVisibleRows;

	const isVisible = i >= minVisible && i <= maxVisible;

	if (isVisible) {
		if (sprite.opacity > unselectedOpacity) {
			sprite.opacity = Math.max(unselectedOpacity, sprite.opacity - fadeDelta);
		} else if (sprite.opacity < unselectedOpacity) {
			sprite.opacity = Math.min(unselectedOpacity, sprite.opacity + fadeDelta);
		}
	} else {
		if (sprite.opacity > hiddenOpacity) {
			sprite.opacity = Math.max(hiddenOpacity, sprite.opacity - fadeDelta);
		}
	}

	if (sprite.scale.x > 1) {
		sprite.scale.x = Math.max(1, sprite.scale.x - this.com_zoom_speed() * delta);
	}
};

//==============================
// * Update Zoom Effect
//==============================
Window_ActorCommand.prototype.update_zoom_effect = function (i) {
	const zoomSpeed = this.com_zoom_speed() * 60 * SceneManager._deltaTime;
	const spriteScale = this._com_sprites[i].scale;
	if (this._zoom[0] === 0) {
		const maxZoom = this.com_zoom_rate();
		if (spriteScale.x < maxZoom) {
			spriteScale.x = Math.min(maxZoom, spriteScale.x + zoomSpeed);
		}
		if (this._loop_zoom_effect && spriteScale.x >= maxZoom) {
			this._zoom[0] = 1;
		}
	} else {
		const minZoom = 1;
		spriteScale.x = Math.max(minZoom, spriteScale.x - zoomSpeed);
		if (spriteScale.x <= minZoom) {
			this._zoom[0] = 0;
		}
	}
};

//==============================
// * Process Touch
//==============================
Window_ActorCommand.prototype.processTouch = function() {
    if (this.isOpenAndActive()) {
		if (TouchInput.isCancelled()) {
            if (this.isCancelEnabled()) {
                this.processCancel();
            };
		} else if (TouchInput.isTriggered() && this.isTouchedInsideCom()) {
			this.sel_time = 5;
        };
	};
};

//==============================
// * Process Touch
//==============================
Window_ActorCommand.prototype.isTouchedInsideCom = function() {
	for (var i = 0; i < this._com_sprites.length; i++) {
		if (this._com_sprites[i].visible && this._com_sprites[i].opacity > 25) {
		if (TouchInput.x > this.x + this._com_sprites[i].x - (this._com_sprites[i].bitmap.width / 2) &&
		    TouchInput.x < this.x + this._com_sprites[i].x + this._com_sprites[i].bitmap.width - (this._com_sprites[i].bitmap.width / 2) &&
 		    TouchInput.y > this.y + this._com_sprites[i].y - (this._com_sprites[i].bitmap.height / 2) &&
			TouchInput.y < this.y + this._com_sprites[i].y + this._com_sprites[i].bitmap.height - (this._com_sprites[i].bitmap.height / 2))
			{this._index = i ;return true};
	    };
	};
	return false;
};

